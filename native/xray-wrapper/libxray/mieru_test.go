func TestNormalizeMieruLink(t *testing.T) {
	profile := &pb.ClientProfile{ProfileName: proto.String("mieru + 中文"),
		User: &pb.User{Name: proto.String("user+name"), Password: proto.String("p@ss:word")},
		Servers: []*pb.ServerEndpoint{
			{DomainName: proto.String("proxy.example.com"), PortBindings: []*pb.PortBinding{{Port: proto.Int32(12345), Protocol: pb.TransportProtocol_TCP.Enum()}}},
			{IpAddress: proto.String("::1"), PortBindings: []*pb.PortBinding{{PortRange: proto.String("12345-12347"), Protocol: pb.TransportProtocol_UDP.Enum()}}},
		}, Mtu: proto.Int32(1400), HandshakeMode: pb.HandshakeMode_HANDSHAKE_NO_WAIT.Enum(),
		Multiplexing: &pb.MultiplexingConfig{Level: pb.MultiplexingLevel_MULTIPLEXING_HIGH.Enum()}}
	link, err := appctl.ClientConfigToURL(&pb.ClientConfig{Profiles: []*pb.ClientProfile{profile, proto.Clone(profile).(*pb.ClientProfile)}})
	if err != nil {
		t.Fatal(err)
	}
	normalized, err := NormalizeMieruLink(link)
	if err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(normalized, "\n")
	if len(lines) != 4 {
		t.Fatalf("lost profiles or servers: %d", len(lines))
	}
	for _, line := range lines {
		decoded, err := appctl.URLToClientProfile(line)
		if err != nil {
			t.Fatal(err)
		}
		if decoded.GetUser().GetPassword() != profile.GetUser().GetPassword() || decoded.GetMtu() != 1400 || decoded.GetProfileName() != profile.GetProfileName() {
			t.Fatalf("profile options lost: %v", decoded)
		}
	}
	for _, bad := range []string{"mieru://%%%", "mieru://", "mierus://user:pass@host"} {
		if _, err := NormalizeMieruLink(bad); err == nil {
			t.Fatalf("accepted invalid link: %s", bad)
		}
	}
	// Shared with Android's real native codec test, generated by official protobuf encoder.
	t.Logf("official fixture: %s", link)
	parsed, _ := url.Parse(lines[0])
	if parsed.Query().Get("multiplexing") != "MULTIPLEXING_HIGH" {
		t.Fatal("multiplexing lost")
	}
}

func TestMieruEncryptedTCPAndUDP(t *testing.T) {
	for _, transport := range []pb.TransportProtocol{pb.TransportProtocol_TCP, pb.TransportProtocol_UDP} {
		for _, mtu := range []int{0, 1400} {
			t.Run(fmt.Sprintf("%s/mtu%d", transport, mtu), func(t *testing.T) {
				// Reserve an ephemeral port using the appropriate transport.
				var port int
				if transport == pb.TransportProtocol_TCP {
					l, err := net.Listen("tcp", "127.0.0.1:0")
					if err != nil {
						t.Fatal(err)
					}
					port = l.Addr().(*net.TCPAddr).Port
					l.Close()
				} else {
					l, err := net.ListenPacket("udp", "127.0.0.1:0")
					if err != nil {
						t.Fatal(err)
					}
					port = l.LocalAddr().(*net.UDPAddr).Port
					l.Close()
				}
				server := mieruserver.NewServer()
				err := server.Store(&mieruserver.ServerConfig{Config: &pb.ServerConfig{
					ListenIPAddress: proto.String("127.0.0.1"),
					PortBindings:    []*pb.PortBinding{{Port: proto.Int32(int32(port)), Protocol: transport.Enum()}},
					Users:           []*pb.User{{Name: proto.String("user"), Password: proto.String("secret")}},
				}})
				if err != nil {
					t.Fatal(err)
				}
				if err = server.Start(); err != nil {
					t.Fatal(err)
				}
				defer server.Stop()
				requests := make(chan string, 8)
				go func() {
					for {
						conn, req, err := server.Accept()
						if err != nil {
							return
						}
						go func() {
							defer conn.Close()
							conn.SetDeadline(time.Now().Add(10 * time.Second))
							requests <- req.DstAddr.String()
							if err := mierumodel.WriteSocks5Response(conn, 0, mierumodel.AddrSpec{IP: net.IPv4(127, 0, 0, 1), Port: port}); err != nil {
								return
							}
							if req.Command == 1 {
								if _, err := http.ReadRequest(bufio.NewReader(conn)); err != nil {
									return
								}
								fmt.Fprint(conn, "HTTP/1.1 204 No Content\r\nConnection: close\r\n\r\n")
							} else if req.Command == 3 {
								packet := mierucommon.NewUDPAssociateWrapper(mierucommon.NewPacketOverStreamTunnel(conn))
								buffer := make([]byte, 65535)
								for {
									n, addr, err := packet.ReadFrom(buffer)
									if err != nil {
										return
									}
									if _, err := packet.WriteTo(buffer[:n], addr); err != nil {
										return
									}
								}
							}
						}()
					}
				}()
				options := map[string]any{"type": "mieru", "port": port, "username": "user", "password": "secret", "transport": transport.String(), "multiplexing": "MULTIPLEXING_LOW"}
				if mtu != 0 {
					options["mtu"] = mtu
					options["handshake-mode"] = "HANDSHAKE_NO_WAIT"
				}
				config := adapterConfig(options)
				if _, err := MeasureDelay(config, "http://iceflow.invalid/generate_204", 10000); err != nil {
					t.Fatalf("encrypted TCP: %v", err)
				}
				select {
				case target := <-requests:
					if target != "iceflow.invalid:80" {
						t.Fatalf("wrong destination: %s", target)
					}
				case <-time.After(time.Second):
					t.Fatal("proxy bypassed")
				}
				inst, err := newInstance(config)
				if err != nil {
					t.Fatal(err)
				}
				defer inst.Close()
				if err = inst.Start(); err != nil {
					t.Fatal(err)
				}
				ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
				defer cancel()
				dest, _ := XN.ParseDestination("udp:127.0.0.1:9999")
				conn, err := core.Dial(ctx, inst, dest)
				if err != nil {
					t.Fatal(err)
				}
				defer conn.Close()
				conn.SetDeadline(time.Now().Add(10 * time.Second))
				for _, size := range []int{17, 4096, 17} {
					payload := []byte(strings.Repeat("x", size))
					if _, err := conn.Write(payload); err != nil {
						t.Fatal(err)
					}
					buffer := make([]byte, 65535)
					n, err := conn.Read(buffer)
					if err != nil {
						t.Fatalf("encrypted UDP: %v", err)
					}
					if string(buffer[:n]) != string(payload) {
						t.Fatalf("UDP data changed: %d != %d", n, size)
					}
				}
			})
		}
	}
}
